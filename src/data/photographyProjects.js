export const PHOTOGRAPHY_CATEGORY_ORDER = ['Match Day', 'Portraits', 'Tournament Weekend', 'Detail Study'];

export function groupPhotographyByCategory(projects) {
  const groups = new Map();
  for (const p of projects) {
    const key = p.category || 'More Work';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(p);
  }
  const ordered = [
    ...PHOTOGRAPHY_CATEGORY_ORDER,
    ...[...groups.keys()].filter((k) => !PHOTOGRAPHY_CATEGORY_ORDER.includes(k)),
  ];
  return ordered.filter((k) => groups.has(k)).map((k) => [k, groups.get(k)]);
}

export function slugifyCategory(category) {
  return category.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}
